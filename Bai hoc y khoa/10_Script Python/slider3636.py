def _timeline_horizontal(prs, d, ctx):
    """Mốc thời gian ngang"""
    T = _T()
    s = add_blank_slide(prs)
    slide_bg(s)
    slide_header(s, d.get("title", "Dòng thời gian"))

    events = d.get("events", [])
    n = len(events)
    if n == 0:
        footer(s, ctx["footer_text"], ctx["page_num"], ctx["total"])
        return
    # Đường ngang giữa
    line_y = Inches(4.3)
    rect(s, Inches(0.5), line_y, Inches(12.3), Pt(3), T.ACCENT)
    col_w = 12.3 / n
    for i, ev in enumerate(events):
        cx = 0.5 + col_w * (i + 0.5)
        # Dot
        dot = Inches(0.4)
        rect(s, Inches(cx - 0.2), line_y - Inches(0.18),
             dot, dot, T.ACCENT)
        # Text alternating above/below
        is_above = (i % 2 == 0)
        if is_above:
            ty1, ty2, th = 1.85, 2.45, 1.7
        else:
            ty1, ty2, th = 4.85, 5.5, 1.7
        # Date
        txt(s, ev.get("date", ""),
            Inches(cx - col_w / 2 + 0.1), Inches(ty1),
            Inches(col_w - 0.2), Inches(0.5),
            size=_sizes()["caption"] + 2, bold=True, color=T.ACCENT,
            align=PP_ALIGN.CENTER)
        # Title
        txt(s, ev.get("title", ""),
            Inches(cx - col_w / 2 + 0.1), Inches(ty2),
            Inches(col_w - 0.2), Inches(0.5),
            size=_sizes()["body"] - 1, bold=True, color=T.INK,
            autofit=True, min_size=10, align=PP_ALIGN.CENTER)
        # Description
        if ev.get("description"):
            txt(s, ev["description"],
                Inches(cx - col_w / 2 + 0.1), Inches(ty2 + 0.5),
                Inches(col_w - 0.2), Inches(th - 1.0),
                size=_sizes()["caption"] + 1, color=T.MUTED,
                autofit=True, min_size=9,
                align=PP_ALIGN.CENTER, wrap=True)
    footer(s, ctx["footer_text"], ctx["page_num"], ctx["total"])

