def _estimate_lines(text, chars_per_line):
    """Đếm số dòng sau khi word-wrap với chars_per_line"""
    if not text or chars_per_line <= 0:
        return 0
    total = 0
    for paragraph in str(text).split("\n"):
        if not paragraph.strip():
            total += 1
            continue
        words = paragraph.split()
        if not words:
            total += 1
            continue
        cur, lines = 0, 1
        for w in words:
            wl = len(w) + (1 if cur > 0 else 0)
            if cur + wl > chars_per_line:
                if len(w) > chars_per_line:
                    extra = len(w) // chars_per_line
                    lines += extra + (1 if cur > 0 else 0)
                    cur = len(w) % chars_per_line
                else:
                    lines += 1
                    cur = len(w)
            else:
                cur += wl
        total += lines
    return total

def fit_text_size(text, box_w, box_h, initial_size,
                  min_size=8, bold=False, line_factor=1.25,
                  padding_pt=8):
    """Auto-shrink size để text vừa box.

    Args:
        text: chuỗi
        box_w, box_h: Emu/Inches/float (inches)
        initial_size: cỡ ban đầu (pt)
        min_size: cỡ tối thiểu (pt)

    Returns: int — size cuối cùng (pt)
    """
    if not text:
        return initial_size

    box_w_pt = _emu_to_inches(box_w) * 72 - padding_pt
    box_h_pt = _emu_to_inches(box_h) * 72 - padding_pt * 0.5

    if box_w_pt <= 0 or box_h_pt <= 0:
        return min_size

    char_factor = 0.58 if bold else 0.52
    size = int(initial_size)

    while size >= min_size:
        avg_w = size * char_factor
        cpl = max(1, int(box_w_pt / avg_w))
        lines = _estimate_lines(str(text), cpl)
        line_h = size * line_factor
        if lines * line_h <= box_h_pt:
            return size
        size -= 1
    return min_size

def fit_bullet_list_size(points, box_w, box_h, initial_size,
                         min_size=9, line_factor=1.35, gap_pt=4):
    """Auto-fit cho danh sách bullet — tính tổng chiều cao tất cả điểm"""
    if not points:
        return initial_size
    box_w_pt = _emu_to_inches(box_w) * 72 - 16
    box_h_pt = _emu_to_inches(box_h) * 72 - 8
    if box_w_pt <= 0 or box_h_pt <= 0:
        return min_size

    char_factor = 0.52
    size = int(initial_size)
    while size >= min_size:
        avg_w = size * char_factor
        cpl = max(1, int(box_w_pt / avg_w))
        line_h = size * line_factor
        total = 0
        for p in points:
            # +3 cho prefix "  – "
            lines = _estimate_lines("    " + str(p), cpl)
            total += lines * line_h + gap_pt
        if total <= box_h_pt:
            return size
        size -= 1
    return min_size

