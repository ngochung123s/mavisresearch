from pptx.chart.data import CategoryChartData
from pptx.enum.chart import XL_CHART_TYPE, XL_LEGEND_POSITION

PPTX_CHART_TYPES = {
    "bar_clustered":   XL_CHART_TYPE.COLUMN_CLUSTERED,
    "bar_stacked":     XL_CHART_TYPE.COLUMN_STACKED,
    "bar_horizontal":  XL_CHART_TYPE.BAR_CLUSTERED,
    "line":            XL_CHART_TYPE.LINE_MARKERS,
    "pie":             XL_CHART_TYPE.PIE,
}

def _build_chart(sl, chart_type, categories, series_list,
                 x, y, w, h, show_legend=True, T=None):
    if T is None:
        T = _T()
    ct = PPTX_CHART_TYPES.get(chart_type)
    if ct is None:
        return None
    chart_data = CategoryChartData()
    chart_data.categories = categories
    for s in series_list:
        chart_data.add_series(s.get("name", ""), s.get("values", []))
    frame = sl.shapes.add_chart(ct, x, y, w, h, chart_data)
    chart = frame.chart
    chart.has_legend = show_legend
    if show_legend:
        chart.legend.position = XL_LEGEND_POSITION.BOTTOM
        chart.legend.include_in_layout = False
    accent_colors = [T.ACCENT, T.ACCENT2, T.SUCCESS, T.WARNING, T.DANGER, T.GOLD]
    for i, ser in enumerate(chart.series):
        ser.format.fill.solid()
        ser.format.fill.fore_color.rgb = accent_colors[i % len(accent_colors)]
    if chart_type in ("bar_clustered", "bar_stacked", "bar_horizontal"):
        plot = chart.plots[0]
        plot.has_data_labels = True
        dl = plot.data_labels
        dl.font.size = Pt(9)
        dl.font.color.rgb = T.BODY
        dl.number_format = '0'
        dl.show_value = True
    return frame

