def validate_slide(slide, idx):
    """Trả về list lỗi (rỗng nếu hợp lệ)"""
    errors = []
    label = f"Slide #{idx+1}"

    if not isinstance(slide, dict):
        return [f"{label}: phải là object JSON"]

    stype = slide.get("type")
    if not stype:
        return [f"{label}: thiếu field 'type'"]

    if stype not in SCHEMAS:
        valid_types = ", ".join(SCHEMAS.keys())
        return [f"{label}: type '{stype}' không hợp lệ. Có sẵn: {valid_types}"]

    schema = SCHEMAS[stype]
    label = f"{label} [{stype}]"

    # Required fields
    for f in schema["required"]:
        if f not in slide:
            errors.append(f"{label}: thiếu field bắt buộc '{f}'")
        elif slide[f] in (None, "", []):
            errors.append(f"{label}: field '{f}' đang trống")

    # Field types
    for f, t in schema.get("field_types", {}).items():
        if f in slide and slide[f] is not None:
            if not isinstance(slide[f], t):
                errors.append(
                    f"{label}: '{f}' phải là {t.__name__}, "
                    f"nhận được {type(slide[f]).__name__}"
                )

    # Variant
    variant = slide.get("variant")
    if variant and variant not in schema["variants"]:
        errors.append(
            f"{label}: variant '{variant}' không hợp lệ. "
            f"Có sẵn: {', '.join(schema['variants'])}"
        )

    # Unknown fields (warning only, không phải error)
    known = set(schema["required"]) | set(schema.get("optional", [])) | {"type"}
    unknown = set(slide.keys()) - known
    if unknown:
        errors.append(
            f"⚠ {label}: field không nhận diện: {', '.join(unknown)} "
            f"(sẽ bị bỏ qua)"
        )

    title = slide.get("title") or slide.get("part_title")
    if isinstance(title, str) and len(title) > 95:
        errors.append(f"⚠ {label}: title dài >95 ký tự; nên rút gọn để slide thoáng hơn")

    list_fields = [
        "points", "objectives", "takeaways", "left_points", "right_points",
        "major", "minor", "items", "steps", "refs",
    ]
    for f in list_fields:
        val = slide.get(f)
        if isinstance(val, list):
            if len(val) > 8:
                errors.append(f"⚠ {label}: '{f}' có {len(val)} mục; nên tách slide hoặc đổi layout")
            for item in val:
                text = str(item)
                if len(text.split()) > 32:
                    errors.append(f"⚠ {label}: một mục trong '{f}' >32 từ; nên chuyển bớt vào speaker note")
                    break

    return errors

def validate_deck(slides):
    """Validate toàn bộ deck. Trả về (errors, warnings)"""
    errors, warnings = [], []
    if not isinstance(slides, list):
        return ["Slides phải là list"], []
    if not slides:
        return ["Deck trống"], []

    for i, s in enumerate(slides):
        msgs = validate_slide(s, i)
        for m in msgs:
            if m.startswith("⚠"):
                warnings.append(m)
            else:
                errors.append(m)

    first_type = slides[0].get("type") if isinstance(slides[0], dict) else None
    if first_type != "title":
        warnings.append("⚠ Deck: slide đầu không phải type 'title'")

    if len(slides) < 5:
        warnings.append("⚠ Deck: dưới 5 slide; có thể quá ngắn cho bài giảng y khoa")
    elif len(slides) > 35:
        warnings.append("⚠ Deck: trên 35 slide; nên cân nhắc tách thành nhiều phần")

    has_refs = any(isinstance(s, dict) and s.get("type") == "references" for s in slides)
    deck_text = json.dumps(slides, ensure_ascii=False)
    citation_like = re.search(r"PMID|\[(?:ACOG|ASRM|ESHRE|RCOG|ISUOG|FIGO|NICE|WHO|ISSHP)", deck_text)
    if citation_like and not has_refs:
        warnings.append("⚠ Deck: có PMID/guideline nhưng chưa có slide references")
    return errors, warnings


