def _build_table(s, headers, rows, x, y, w, h, T,
                 highlight_col=None, base_size_offset=-3):
    n_cols = len(headers)
    n_rows = len(rows) + 1
    if n_cols == 0 or n_rows == 0: return
    row_h = min(Inches(0.65), h / n_rows)
    tbl = s.shapes.add_table(n_rows, n_cols, x, y, w, row_h * n_rows).table
    base = _sizes()["body"] + base_size_offset
    if len(rows) > 8: base = max(9, base - 1)
    # Header
    for ci, hd in enumerate(headers):
        cell = tbl.cell(0, ci)
        cell.fill.solid()
        cell.fill.fore_color.rgb = T.INK
        p = cell.text_frame.paragraphs[0]
        p.alignment = PP_ALIGN.CENTER
        r = p.add_run()
        r.text = str(hd)
        r.font.size = Pt(base)
        r.font.bold = True
        r.font.color.rgb = T.WHITE
        r.font.name = _font()
    # Rows
    for ri, row in enumerate(rows):
        bg = T.CARD if ri % 2 == 0 else T.WHITE
        for ci, val in enumerate(row):
            cell = tbl.cell(ri + 1, ci)
            cell.fill.solid()
            cell.fill.fore_color.rgb = (T.ACCENT2 if ci == highlight_col else bg)
            p = cell.text_frame.paragraphs[0]
            p.alignment = PP_ALIGN.CENTER
            r = p.add_run()
            r.text = str(val)
            r.font.size = Pt(base - 1)
            r.font.bold = (ci == highlight_col)
            r.font.color.rgb = T.WHITE if ci == highlight_col else T.BODY
            r.font.name = _font()

