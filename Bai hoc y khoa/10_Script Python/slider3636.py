def _outline_tree(prs, d, ctx):
    """Cây nội dung phân cấp 2 mức: chương + sub-points"""
    T = _T()
    s = add_blank_slide(prs)
    slide_bg(s)
    slide_header(s, d.get("title", _L("outline_default")))

    chapters = d.get("chapters", [])
    if not chapters:
        footer(s, ctx["footer_text"], ctx["page_num"], ctx["total"])
        return
    # Chia 2 cột nếu > 3 chương
    half = (len(chapters) + 1) // 2 if len(chapters) > 3 else len(chapters)
    cols = [chapters[:half], chapters[half:]] if len(chapters) > 3 else [chapters, []]
    col_w = Inches(6.1)

    for col_i, col in enumerate(cols):
        x0 = Inches(0.4 + col_i * 6.4)
        y_cursor = Inches(1.75)
        for i, ch in enumerate(col):
            global_idx = i + (half if col_i == 1 else 0)
            title_text = ch if isinstance(ch, str) else ch.get("title", "")
            subs = ch.get("sub", []) if isinstance(ch, dict) else []
            # Header chapter
            badge_w = Inches(0.5)
            rect(s, x0, y_cursor, badge_w, Inches(0.4), T.ACCENT)
            txt(s, str(global_idx + 1),
                x0, y_cursor, badge_w, Inches(0.4),
                size=14, bold=True, color=T.WHITE,
                align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
            txt(s, title_text,
                x0 + Inches(0.6), y_cursor, col_w - Inches(0.6), Inches(0.4),
                size=_sizes()["body"], bold=True, color=T.INK,
                autofit=True, min_size=12, anchor=MSO_ANCHOR.MIDDLE)
            y_cursor += Inches(0.45)
            # Sub items
            for sub in subs:
                txt(s, f"  └  {sub}",
                    x0 + Inches(0.3), y_cursor, col_w - Inches(0.3), Inches(0.32),
                    size=_sizes()["caption"] + 2, color=T.MUTED,
                    autofit=True, min_size=9)
                y_cursor += Inches(0.32)
            y_cursor += Inches(0.1)
    footer(s, ctx["footer_text"], ctx["page_num"], ctx["total"])

